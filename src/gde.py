def get_retrieval_info(
    eval_annotations,
    query_id,
    ref_position=0,
    topk=5,
    alpha=None,
    rho=None,
):
    """
    Compute retrieval results for one query-reference pair.
    Returns everything needed for visualization and ranking.
    """

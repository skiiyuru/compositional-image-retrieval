def compute_similarity(query, db, ref_idx, k=10):
    # (19k,512)*(512,1)
    score = db @ query.T

    # modify the score of ref_img to eliminate it from top-k
    score[ref_idx] = -inf
    sorted_scores, img_idxs = torch.sort(score, dim=0, descending=True)
    top_k = (torch.flatten(img_idxs[:k])).tolist()

